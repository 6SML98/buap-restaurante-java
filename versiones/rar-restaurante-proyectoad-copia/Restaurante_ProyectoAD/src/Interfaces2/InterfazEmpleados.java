    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
         // Obtener el nombre y la ID ingresados en los JTextField
    String nombreBuscado = TextNombreConsulta.getText();
    String idBuscada = textIdIngresar.getText();
    
    if(nombreBuscado.isEmpty() || idBuscada.isEmpty()){
        JOptionPane.showMessageDialog(this, "Por favor llene los campos solicitados");
    }
    
    // Intentar encontrar el empleado en el archivo
    try {
        FileReader fr = new FileReader("empleados.txt");
        BufferedReader br = new BufferedReader(fr);
        String linea;
        boolean encontrado = false;

        while ((linea = br.readLine()) != null) {
            // Verificar si la línea contiene el nombre y la ID buscados
            if (linea.contains("nombre=" + nombreBuscado) && linea.contains("idEmpleado=" + idBuscada)) {
                // Extraer el turno, puesto y salario de la línea
                String turno = obtenerValor(linea, "Turno Laboral");
                String puesto = obtenerValor(linea, "puesto");
                String salario = obtenerSalario(linea);

                // Mostrar la información encontrada
                mostrarInformacion(turno, puesto, salario);
                encontrado = true;
                break;
            }
        }

        if (!encontrado) {
            // Mostrar un mensaje si el empleado no se encuentra
            JOptionPane.showMessageDialog(null, "No se encontró al empleado.", "Error", JOptionPane.ERROR_MESSAGE);
        }

        br.close();
        fr.close();
    } catch (IOException e) {
        // Manejar cualquier error de lectura del archivo
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Error al leer el archivo.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnConsultarActionPerformed

