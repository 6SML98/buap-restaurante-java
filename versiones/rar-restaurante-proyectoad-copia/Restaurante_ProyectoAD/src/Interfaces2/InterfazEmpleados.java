    // Método para extraer el valor de una clave en una línea
    private String obtenerValor(String linea, String clave) {
        int inicio = linea.indexOf(clave + "=") + clave.length() + 1;
        int fin = linea.indexOf(",", inicio);
        if (fin == -1) {
            fin = linea.length() - 1;
        }
        return linea.substring(inicio, fin);
    }
    
   

// Método específico para obtener el salario de una línea utilizando expresiones regulares
private String obtenerSalario(String linea) {
    // Definir el patrón para encontrar el salario
    Pattern patronSalario = Pattern.compile("\\$([0-9,.]+)"); // Busca un signo de dólar seguido de uno o más dígitos, puntos o comas
    Matcher matcher = patronSalario.matcher(linea);

    // Buscar el salario utilizando el patrón
    if (matcher.find()) {
        // Extraer el salario y eliminar caracteres no numéricos
        String salarioConSimbolo = matcher.group(1);
        String salarioNumerico = salarioConSimbolo.replaceAll("[^0-9]", "");
        return salarioNumerico; // Devuelve el valor numérico del salario
    } else {
        return ""; // Devuelve una cadena vacía si no se encuentra el salario
    }
}



